package convert

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/viniciusdc/ci-shift/ir"
	"github.com/viniciusdc/ci-shift/schema"
)

// TestCorpus runs pipelines from public projects (testdata/corpus, sources
// in its README) through detection, the source schema and a conversion to
// every other provider. Nobody wrote them for ci-shift, so unlike the golden
// fixtures they show what users bring, including what ci-shift still gets
// wrong. Each outcome is recorded in testdata/corpus/results.txt: the test
// fails when one changes, and `make golden` rewrites the file once the change
// is intended. A panic always fails.
func TestCorpus(t *testing.T) {
	dir := filepath.Join("..", "testdata", "corpus")
	var files []string
	for _, p := range Providers() {
		matches, _ := filepath.Glob(filepath.Join(dir, p.Name(), "*.yml"))
		files = append(files, matches...)
	}
	if len(files) == 0 {
		t.Fatal("no corpus files found")
	}

	var body strings.Builder
	var conversions, failed, invalid, rejected int
	for _, f := range files {
		rel, _ := filepath.Rel(dir, f)
		rel = filepath.ToSlash(rel)
		data, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		from, err := Get(filepath.Dir(rel))
		if err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&body, "\n%s\n", rel)

		detected := ""
		if p, err := Detect(rel, data); err == nil {
			detected = p.Name()
		} else {
			detected = "error: " + firstLine(err)
		}
		fmt.Fprintf(&body, "  %-9s %s\n", "detect", detected)

		check := "valid"
		if issues, err := schema.Validate(from.Name(), data, schema.Options{Embedded: true}); err != nil {
			check = "error: " + firstLine(err)
		} else if len(issues) > 0 {
			check = "invalid: " + issueSummary(issues)
		}
		if check != "valid" {
			rejected++
		}
		fmt.Fprintf(&body, "  %-9s %s\n", "check", check)

		for _, to := range Providers() {
			if to.Name() == from.Name() {
				continue
			}
			conversions++
			res, err := convertSafely(t, rel, data, from.Name(), to.Name())
			if err != nil {
				failed++
				fmt.Fprintf(&body, "  %-9s error: %s\n", to.Name(), firstLine(err))
				continue
			}
			line := fmt.Sprintf("%d jobs, %d warnings", len(res.Pipeline.Jobs), countWarnings(res))
			issues, err := schema.Validate(to.Name(), res.Output, schema.Options{Embedded: true})
			if err != nil {
				t.Fatalf("%s -> %s: validate: %v", rel, to.Name(), err)
			}
			if len(issues) > 0 {
				invalid++
				line += ", invalid: " + issueSummary(issues)
			}
			fmt.Fprintf(&body, "  %-9s %s\n", to.Name(), line)
		}
	}

	got := fmt.Sprintf("# Generated by TestCorpus; run `make golden` to update. Sources: README.md.\n"+
		"# %d files; %d rejected by their own schema.\n"+
		"# %d conversions; %d failed, %d produced output its schema rejects.\n%s",
		len(files), rejected, conversions, failed, invalid, body.String())
	path := filepath.Join(dir, "results.txt")
	if *update {
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run `make golden` to create it)", err)
	}
	if string(want) != got {
		t.Errorf("corpus results changed (run `make golden` if intended)\n%s", diff(string(want), got))
	}
}

// convertSafely converts one corpus file, failing the test on a panic.
func convertSafely(t *testing.T, name string, data []byte, from, to string) (res *Result, err error) {
	t.Helper()
	defer func() {
		if r := recover(); r != nil {
			t.Errorf("%s -> %s: panic: %v", name, to, r)
			err = fmt.Errorf("panic: %v", r)
		}
	}()
	src, _ := Get(from)
	dst, _ := Get(to)
	return Convert(data, src, dst, Options{})
}

func countWarnings(r *Result) int {
	n := 0
	for _, d := range r.Diagnostics {
		if d.Severity == ir.SeverityWarning {
			n++
		}
	}
	return n
}

// issueSummary names the first schema issue and how many follow it.
func issueSummary(issues []schema.Issue) string {
	s := issues[0].String()
	if len(issues) > 1 {
		s += fmt.Sprintf(" (+%d more)", len(issues)-1)
	}
	return s
}

func firstLine(err error) string {
	if err == nil {
		return ""
	}
	s, _, _ := strings.Cut(err.Error(), "\n")
	return s
}
